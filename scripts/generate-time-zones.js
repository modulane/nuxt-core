import { writeFile } from 'node:fs/promises'
import { COUNTRIES } from '../layers/primitives/app/data/countries.ts'

// Writes the time zones of each country of <FormInput type="tel">, from the
// ICU data of Node.js, to layers/primitives/app/data/time-zones.ts. They tell
// which country the visitor is in. Run it again with `node
// scripts/generate-time-zones.js` when the country list changes.

// ICU keeps the old names of some zones, where Firefox reports the current
// ones: both are listed
const RENAMED = {
  'Africa/Asmera': 'Africa/Asmara',
  'America/Buenos_Aires': 'America/Argentina/Buenos_Aires',
  'America/Catamarca': 'America/Argentina/Catamarca',
  'America/Coral_Harbour': 'America/Atikokan',
  'America/Cordoba': 'America/Argentina/Cordoba',
  'America/Godthab': 'America/Nuuk',
  'America/Indianapolis': 'America/Indiana/Indianapolis',
  'America/Jujuy': 'America/Argentina/Jujuy',
  'America/Louisville': 'America/Kentucky/Louisville',
  'America/Mendoza': 'America/Argentina/Mendoza',
  'Asia/Calcutta': 'Asia/Kolkata',
  'Asia/Katmandu': 'Asia/Kathmandu',
  'Asia/Rangoon': 'Asia/Yangon',
  'Asia/Saigon': 'Asia/Ho_Chi_Minh',
  'Atlantic/Faeroe': 'Atlantic/Faroe',
  'Europe/Kiev': 'Europe/Kyiv',
  'Pacific/Enderbury': 'Pacific/Kanton',
  'Pacific/Ponape': 'Pacific/Pohnpei',
  'Pacific/Truk': 'Pacific/Chuuk',
}

const entries = COUNTRIES.map(({ code }) => {
  const locale = new Intl.Locale(`und-${code}`)
  const zones = locale.getTimeZones?.() ?? locale.timeZones ?? []
  const all = zones.flatMap(zone =>
    RENAMED[zone] ? [zone, RENAMED[zone]] : [zone],
  )
  return all.length ? `${code}:${all.join(',')}` : undefined
}).filter(Boolean)

const lines = []
let line = ''
for (const entry of entries) {
  if (line && line.length + entry.length > 70) {
    lines.push(line)
    line = ''
  }
  line += `${entry} `
}
lines.push(line)

const source = `// Generated by scripts/generate-time-zones.js from the ICU data of Node.js
// ${process.versions.node}: do not edit. Each country's time zones, as
// CODE:Zone,Zone, one country after another.
export const TIME_ZONES =
${lines.map(part => `  '${part}'`).join(' +\n')}
`

await writeFile('layers/primitives/app/data/time-zones.ts', source)
